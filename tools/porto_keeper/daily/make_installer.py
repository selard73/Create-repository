"""Generate an Edit-only, preflight-guarded installer. Does not connect to Studio."""
from pathlib import Path
import argparse,hashlib,json
ROOT=Path(__file__).resolve().parent
parser=argparse.ArgumentParser()
parser.add_argument('--upgrade-from')
parser.add_argument('--output',default='install_daily.lua')
parser.add_argument('--backup',default='PortoDailyBackup_20261013')
args=parser.parse_args()
assert args.backup.replace('_','').isalnum()
upgrade=(ROOT/args.upgrade_from) if args.upgrade_from else None
def literal(text):
    level='===='
    assert ']'+level+']' not in text
    return '['+level+'['+text+']'+level+']'
targets=[
 ('keeper','PortoKeeperServer','Script',True),
 ('setup','SquirrelSetup','Script',True),
 ('keeper','PortoKeeperClient','Script',True),
 ('keeper','DailyKeeperCore','ModuleScript',False),
 ('keeper','DailyKeeperStore','ModuleScript',False),
 ('setup','FindsEpoch','ModuleScript',False),
]
rows=[];manifest={}
for parent,name,kind,existing in targets:
    source=(ROOT/(name+'.lua')).read_text(encoding='utf-8')
    baseline=(upgrade/(name+'.lua')).read_text(encoding='utf-8') if upgrade else (ROOT/(name+'.baseline.lua')).read_text(encoding='utf-8') if existing else ''
    existing=existing or upgrade is not None
    rows.append('{parent='+parent+',name='+json.dumps(name)+',class='+json.dumps(kind)+',existing='+str(existing).lower()+',before='+literal(baseline)+',after='+literal(source)+'}')
    manifest[name]={'sha256':hashlib.sha256(source.encode()).hexdigest(),'characters':len(source),'existing':existing}
code='''-- Generated by make_installer.py. Studio Edit only. No DataStore/Play/publish calls.
local RunService = game:GetService("RunService")
assert(RunService:IsStudio() and not RunService:IsRunning(), "Daily install requires Studio Edit")
assert(game.PlaceId == 117372258657114 and game.GameId == 10766369535, "Wrong experience")
local keeper = assert(workspace:FindFirstChild("PortoKeeper"), "Missing PortoKeeper")
local setup = assert(workspace:FindFirstChild("SquirrelScripts"), "Missing SquirrelScripts")
local function normalized(s) return (s:gsub("\\r\\n", "\\n"):gsub("\\n+$", "")) end
local changes = {
'''+',\n'.join(rows)+'''
}
local needed = 0
-- Validate every target and compile every source BEFORE any mutation.
for _,change in ipairs(changes) do
    local target=change.parent:FindFirstChild(change.name)
    if target then
        assert(target.ClassName == change.class, "Unexpected class: " .. change.name)
        change.target=target
        change.original=target.Source
        change.skip=normalized(target.Source)==normalized(change.after)
        if not change.skip then
            assert(change.existing and normalized(target.Source)==normalized(change.before), "Source changed; refusing to overwrite " .. change.name)
        end
    else
        assert(not change.existing, "Missing script " .. change.name)
    end
    local compiled,err=loadstring(change.after)
    assert(compiled, change.name .. ": " .. tostring(err))
    if not change.skip then needed+=1 end
end
if needed==0 then return "Italy daily award sources already match; nothing changed." end
local SS=game:GetService("ServerStorage")
local backupName="PortoDailyBackup_20261013"
assert(not SS:FindFirstChild(backupName), "Backup already exists; review before reinstalling different sources")
local backup=Instance.new("Folder");backup.Name=backupName;backup.Parent=SS
for _,change in ipairs(changes) do
    if change.target and not change.skip then
        local saved=change.target:Clone();saved.Name=change.name
        if saved:IsA("BaseScript") then saved.Enabled=false end
        saved.Parent=backup
    end
end
local applied={}
local ok,err=pcall(function()
    -- Modules are present before modified scripts could ever run in a later session.
    for _,change in ipairs(changes) do
        if not change.skip and not change.target then
            change.target=Instance.new(change.class);change.created=true
            change.target.Name=change.name;change.target.Source=change.after
            table.insert(applied,change)
            change.target.Parent=change.parent
        end
    end
    for _,change in ipairs(changes) do
        if not change.skip and not change.created then
            table.insert(applied,change)
            change.target.Source=change.after
        end
    end
end)
if not ok then
    for i=#applied,1,-1 do
        local change=applied[i]
        if change.created then change.target:Destroy() else change.target.Source=change.original end
    end
    error("Installation rolled back; originals retained in " .. backupName .. ": " .. tostring(err))
end
return "Installed " .. needed .. " source files in Edit only. Originals: ServerStorage." .. backupName .. ". Not published."
'''
code=code.replace('local backupName="PortoDailyBackup_20261013"','local backupName='+json.dumps(args.backup))
(ROOT/args.output).write_text(code,encoding='utf-8')
(ROOT/'source-manifest.json').write_text(json.dumps(manifest,indent=2),encoding='utf-8')
print('Generated guarded installer and manifest for',len(targets),'sources.')
